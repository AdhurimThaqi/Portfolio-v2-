// Collects projects/*/project.json into a module the Netlify functions can import,
// so the public AI assistant always knows the same projects the site shows.
// Runs before `vite build`; the output is generated, not committed.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "projects");
const out = path.join(root, "netlify/functions/lib/projects.generated.mjs");

const projects = fs
  .readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(dir, d.name, "project.json")))
  .map((d) => ({ slug: d.name, ...JSON.parse(fs.readFileSync(path.join(dir, d.name, "project.json"), "utf8")) }))
  .filter((p) => !p.hidden)
  .sort((a, b) => (a.order ?? 99) - (b.order ?? 99));

fs.writeFileSync(out, `// Generated by scripts/gen-projects.mjs. Do not edit.\nexport default ${JSON.stringify(projects, null, 2)};\n`);
console.log(`gen-projects: ${projects.length} projects -> ${path.relative(root, out)}`);
